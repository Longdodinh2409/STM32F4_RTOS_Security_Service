void ProcessDisplayScanning()
{
	static bool bIsInitThisLayout = true;
	static uint16_t u16CurrentStep = 0;
	uint16_t u16CurrentY;

	if (bIsInitThisLayout == true)
	{
//		SSD1306_Clear();
		SSD1306_DrawBitmap(2, 0, fingerprint_bitmap, 128, 64, SSD1306_COLOR_WHITE);
		
		SSD1306_SavePrevBitmapAnimation();
		
		u16CurrentStep = 0;
		bIsInitThisLayout = false;
	}

	u16CurrentY = START_Y_SCANNING_BAR + (u16CurrentStep * WIDTH_EACH_STEP_SCANNING_ANIMATION);

	if (u16CurrentStep > 0)
	{
		uint16_t u16PrevY = START_Y_SCANNING_BAR + ((u16CurrentStep - 1) * WIDTH_EACH_STEP_SCANNING_ANIMATION);
		SSD1306_RewriteBitmapOfPreviousStep(FIXED_X_SCANNING_BAR, u16PrevY, SSD1306_WIDTH, SSD1306_HEIGHT);
	}
	else if (u16CurrentStep == 0)
	{
		uint16_t u16PrevY = END_Y_SCANNING_BAR - WIDTH_EACH_STEP_SCANNING_ANIMATION;
		SSD1306_RewriteBitmapOfPreviousStep(FIXED_X_SCANNING_BAR, u16PrevY, SSD1306_WIDTH, SSD1306_HEIGHT);
	}

	SSD1306_DrawFilledRectangle(FIXED_X_SCANNING_BAR, u16CurrentY, SCANNING_BAR_WIDTH, SCANNING_BAR_HEIGHT, SSD1306_COLOR_WHITE);

	SSD1306_UpdateScreen();

	u16CurrentStep++;

	if (u16CurrentStep >= TOTAL_STEP_OF_SCANNING_ANIMATION)
	{
		u16CurrentStep = 0;
	}

	vTaskDelay(pdMS_TO_TICKS(75));
}

