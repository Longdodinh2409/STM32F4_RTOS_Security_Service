void ProcessDisplay(uint8_t u8State)
{
	static uint8_t s_u8PrevScreenState = SCREEN_STATE_MAX_CNT;

	if (u8State == INVALID_CMD)
	{
		return;
	}

	if (u8State >= (uint8_t)(SCREEN_STATE_MAX_CNT))
	{
		// Error
		return;
	}

	s_u8ScreenState = (E_SCREEN_STATE)u8State;

	if (s_u8ScreenState != s_u8PrevScreenState)
	{
		SSD1306_Clear();
		s_u8PrevScreenState = s_u8ScreenState;
	}

	  switch(s_u8ScreenState)
	  {
		  case SCREEN_STATE_INIT:
		  {
			  ProcessDisplayInit();
			  s_u8ScreenState = SCREEN_STATE_STANDBY;
		  }
		  break;

		  case SCREEN_STATE_STANDBY:
		  {
			  ProcessDisplayStandby();
		  }
		  break;

		  case SCREEN_STATE_PROCESSING:
		  {
			  ProcessDisplayScanning();
		  }
		  break;

		  case SCREEN_STATE_PASS:
		  {
			  ProcessDisplayPass();
		  }
		  break;

		  case SCREEN_STATE_FAIL:
		  {
			  ProcessDisplayFail();
		  }
		  break;

		  case SCREEN_STATE_TEMP_LOCK:
		  {
			  ProcessDisplayTempLock();
		  }
		  break;

		  case SCREEN_STATE_INFINITY_LOCK:
		  {
			  ProcessDisplayInfLock();
		  }
		  break;


		  default:
			  break;
	  }
}

